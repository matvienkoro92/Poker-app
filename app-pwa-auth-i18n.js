function pokerPwaAuthI18nPack(scope, locale) {
  var group = POKER_PWA_AUTH_I18N && POKER_PWA_AUTH_I18N[scope];
  if (!group) return {};
  return group[locale] || group.ru || {};
}

function pokerPwaAuthText(locale, key) {
  var pack = pokerPwaAuthI18nPack("auth", locale);
  if (pack[key] != null) return pack[key];
  var fallback = pokerPwaAuthI18nPack("auth", "ru");
  return fallback[key] || "";
}
