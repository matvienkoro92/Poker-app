const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const sources = [
  "winter-rating-data.js",
  "spring-rating-data-march.js",
  "spring-rating-data-april.js",
  "spring-rating-data-may.js",
  "summer-rating-data-june.js",
  "summer-rating-data-july.js",
  "summer-rating-data-august.js",
];
const birthdays = [
  { date: "2026-08-03", nick: "Baldendi" },
];
const context = vm.createContext({ window: {}, console, isFinite });
sources.forEach((file) => {
  vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context, { filename: file });
});

function dateStamp(label) {
  const match = String(label || "").match(/^(\d{2})\.(\d{2})\.(\d{4})$/);
  return match ? Number(match[3] + match[2] + match[1]) : 0;
}

function isoLocal(label) {
  const match = String(label || "").match(/^(\d{2})\.(\d{2})\.(\d{4})$/);
  return match ? match[3] + "-" + match[2] + "-" + match[1] + "T12:00:00" : "";
}

const maps = [
  context.WINTER_RATING_TOURNAMENTS_BY_DATE,
  context.SPRING_RATING_TOURNAMENTS_MARCH_BY_DATE,
  context.SPRING_RATING_TOURNAMENTS_APRIL_BY_DATE,
  context.SPRING_RATING_TOURNAMENTS_MAY_BY_DATE,
  context.SUMMER_RATING_TOURNAMENTS_JUNE_BY_DATE,
  context.SUMMER_RATING_TOURNAMENTS_JULY_BY_DATE,
  context.SUMMER_RATING_TOURNAMENTS_AUGUST_BY_DATE,
];
const dated = [];
maps.forEach((map) => {
  Object.keys(map || {}).forEach((label) => {
    (map[label] || []).forEach((tournament) => {
      (Array.isArray(tournament && tournament.players) ? tournament.players : []).forEach((player) => {
        dated.push({
          stamp: dateStamp(label),
          dateLabel: label,
          date: isoLocal(label),
          nick: String(player && player.nick || "").trim(),
          place: Math.max(0, Number(player && player.place) || 0),
          reward: Math.max(0, Number(player && player.reward) || 0),
          tournament: String(tournament && (tournament.name || tournament.time) || "").trim(),
        });
      });
    });
  });
});
Object.keys(context.WINTER_RATING_BY_DATE || {}).forEach((label) => {
  if (Array.isArray(context.WINTER_RATING_TOURNAMENTS_BY_DATE && context.WINTER_RATING_TOURNAMENTS_BY_DATE[label]) && context.WINTER_RATING_TOURNAMENTS_BY_DATE[label].length) return;
  const rows = Array.isArray(context.WINTER_RATING_BY_DATE[label]) ? context.WINTER_RATING_BY_DATE[label].slice() : [];
  rows.filter((player) => (Number(player && player.reward) || 0) > 0)
    .sort((a, b) => (Number(b && b.reward) || 0) - (Number(a && a.reward) || 0))
    .forEach((player, index) => {
      dated.push({
        stamp: dateStamp(label),
        dateLabel: label,
        date: isoLocal(label),
        nick: String(player && player.nick || "").trim(),
        place: index + 1,
        reward: Math.max(0, Number(player && player.reward) || 0),
        tournament: "Дневной итог",
      });
    });
});
dated.sort((a, b) => a.stamp - b.stamp);
const counters = Object.create(null);
dated.forEach((row) => {
  const key = row.nick.toLocaleLowerCase("ru").replace(/\s+/g, "");
  const state = counters[key] || (counters[key] = { first: 0, big50: 0, big100: 0, total: 0 });
  if (row.place === 1) state.first += 1;
  if (row.reward >= 100000) state.big100 += 1;
  else if (row.reward >= 50000) state.big50 += 1;
  state.total += row.reward;
  row.nickKey = key;
  row.firstPlacesCount = state.first;
  row.bigWins50Count = state.big50;
  row.bigWins100Count = state.big100;
  row.totalReward = state.total;
  delete row.stamp;
});
const latest = dated.length ? dated[dated.length - 1].dateLabel : "";
const recentDates = [...new Set(dated.map((row) => row.dateLabel).filter(Boolean))].slice(-2);
const rows = dated.filter((row) => recentDates.includes(row.dateLabel));
const dailyBestWins = Object.create(null);
dated.forEach((row) => {
  if (!row.dateLabel || !row.nickKey || row.reward <= 0) return;
  const day = dailyBestWins[row.dateLabel] || (dailyBestWins[row.dateLabel] = Object.create(null));
  const current = day[row.nickKey];
  if (!current || row.reward > current.reward) {
    day[row.nickKey] = { nick: row.nick, nickKey: row.nickKey, reward: row.reward, tournament: row.tournament };
  }
});
const dayHeroes = Object.create(null);
Object.keys(dailyBestWins).forEach((dateLabel) => {
  const hero = Object.values(dailyBestWins[dateLabel]).sort((a, b) => b.reward - a.reward || a.nick.localeCompare(b.nick, "ru"))[0];
  if (hero) dayHeroes[dateLabel] = hero;
});
const output = "/* Generated by scripts/generate-club-news-data.js. */\n" +
  "window.POKER_CLUB_NEWS_DATA = " + JSON.stringify({ latestDate: latest, rows, dayHeroes, birthdays }) + ";\n";
fs.writeFileSync(path.join(root, "club-news-data.js"), output);
console.log("Generated club-news-data.js with", rows.length, "recent player results");
