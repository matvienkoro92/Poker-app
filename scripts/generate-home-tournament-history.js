#!/usr/bin/env node
// Keep the seven evening tournament histories in sync with the rating records.
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const sources = [
  ["spring-rating-data-march.js", "SPRING_RATING_TOURNAMENTS_MARCH_BY_DATE"],
  ["spring-rating-data-april.js", "SPRING_RATING_TOURNAMENTS_APRIL_BY_DATE"],
  ["spring-rating-data-may.js", "SPRING_RATING_TOURNAMENTS_MAY_BY_DATE"],
  ["summer-rating-data-june.js", "SUMMER_RATING_TOURNAMENTS_JUNE_BY_DATE"],
  ["summer-rating-data-july.js", "SUMMER_RATING_TOURNAMENTS_JULY_BY_DATE"],
  ["summer-rating-data-august.js", "SUMMER_RATING_TOURNAMENTS_AUGUST_BY_DATE"],
  ["summer-rating-data-september.js", "SUMMER_RATING_TOURNAMENTS_SEPTEMBER_BY_DATE"],
];
const tournaments = {
  0: { buyin: 2000, name: /^Воскресн[ыи]й турнир(?:\s|$)/iu },
  1: { buyin: 500, name: /^Турнир Понедельника(?:\s|$)/iu },
  2: { buyin: 300, name: /^Турнир Вторника(?:\s|$)/iu },
  3: { buyin: 1000, name: /^Счастливый Косарь$/iu },
  4: { buyin: 300, name: /^(?:Турнир Четверга(?:\s|$)|Четверг МК[ОO](?:\s|$)|Магия Тракториста)/iu },
  5: { buyin: 500, name: /^Пятница Прогрессив$/iu },
  6: { buyin: 5000, name: /Big Boss/iu, weekdays: [3, 6], historyDays: "СР и СБ" },
};

const context = vm.createContext({});
for (const [file] of sources) {
  vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context, { filename: file });
}

const history = Object.fromEntries(Object.entries(tournaments).map(([day, config]) => [day, {
  buyin: config.buyin,
  ...(config.historyDays ? { historyDays: config.historyDays } : {}),
  results: [],
}]));
for (const [, variable] of sources) {
  for (const [date, entries] of Object.entries(context[variable] || {})) {
    const match = date.match(/^(\d{2})\.(\d{2})\.(2026)$/);
    if (!match || !Array.isArray(entries)) continue;
    const weekday = new Date(Date.UTC(+match[3], +match[2] - 1, +match[1])).getUTCDay();
    for (const entry of entries) {
      const target = Object.entries(tournaments).find(([day, config]) =>
        (config.weekdays || [Number(day)]).includes(weekday) &&
        entry && entry.time === "18:00" && Number(entry.buyin) === config.buyin &&
        config.name.test(String(entry.name || "")));
      if (!target) continue;
      const podium = (Array.isArray(entry.players) ? entry.players : [])
        .filter((player) => player && Number.isInteger(Number(player.place)) &&
          Number(player.place) >= 1 && Number(player.place) <= 3 &&
          String(player.nick || "").trim() && Number(player.reward) > 0)
        .map((player) => [Number(player.place), String(player.nick).trim(), Number(player.reward)])
        .sort((a, b) => a[0] - b[0]);
      if (podium.length) history[target[0]].results.push([date, podium]);
    }
  }
}

for (const item of Object.values(history)) {
  item.results.sort((a, b) => {
    const dateKey = (value) => value.slice(6) + value.slice(3, 5) + value.slice(0, 2);
    return dateKey(a[0]).localeCompare(dateKey(b[0]));
  });
}

const output = "// Generated by scripts/generate-home-tournament-history.js.\n" +
  "var HOME_TOURNAMENT_HISTORY_BY_WEEKDAY = " + JSON.stringify(history, null, 2) + ";\n";
fs.writeFileSync(path.join(root, "app-tournament-history-data.js"), output);
console.log("Evening tournament history: " + Object.entries(history)
  .map(([day, item]) => day + "=" + item.results.length).join(", "));
