"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.join(__dirname, "..");
const context = vm.createContext({});
const totals = { reward: 0, tournaments: 0, high: 0, mid: 0 };
for (const month of ["june", "july", "august"]) {
  const file = `summer-rating-data-${month}.js`;
  vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context, { filename: file });
  const dates = context[`SUMMER_RATING_TOURNAMENTS_${month.toUpperCase()}_BY_DATE`];
  for (const [date, tournaments] of Object.entries(dates)) {
    if (!/^\d{2}\.(06|07|08)\.2026$/.test(date)) continue;
    totals.tournaments += tournaments.length;
    for (const tournament of tournaments) for (const player of tournament.players || []) {
      const reward = Math.max(0, Number(player.reward) || 0);
      totals.reward += reward;
      if (reward >= 100000) totals.high++;
      else if (reward >= 50000) totals.mid++;
    }
  }
}
// Reuse the rating's statistics and markup so both surfaces stay identical.
const adapter = fs.readFileSync(path.join(root, "app-rating-view-adapter.js"), "utf8");
const shared = adapter.slice(0, adapter.indexOf("// Rating view adapter:"));
context.formatRewardRound = n => Math.round(Number(n) || 0).toLocaleString("ru-RU");
context.escapeHtmlRating = value => String(value == null ? "" : value).replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
vm.runInContext(shared, context);
const allDates = Object.assign({}, context.SUMMER_RATING_TOURNAMENTS_JUNE_BY_DATE, context.SUMMER_RATING_TOURNAMENTS_JULY_BY_DATE, context.SUMMER_RATING_TOURNAMENTS_AUGUST_BY_DATE);
const homeStats = context.summerRatingSeasonStats(allDates);
homeStats.topPlayers = homeStats.topPlayers.slice(0, 3);
homeStats.topWins = homeStats.topWins.slice(0, 3);
const homeMarkup = context.summerRatingSeasonStatsHtml(homeStats)
  .replace(/Топ-10/g, "Топ-3")
  .replace(/<div class="summer-results-metrics">[\s\S]*?(?=<div class="summer-rating-season-tops">)/, "");
const html = '<div class="home-summer-dashboard">' + homeMarkup + '<a href="#" data-view-target="summer-rating">Полный рейтинг лета →</a></div>';
const ratingCss = fs.readFileSync(path.join(root, "styles-rating-late.css"), "utf8");
const baseStart = ratingCss.indexOf(".summer-rating-season-counts {");
const baseEnd = ratingCss.indexOf(" .summer-rating-season-spoiler", baseStart);
const dashboardStart = ratingCss.indexOf("/* Summer results dashboard");
const sharedCss = (ratingCss.slice(baseStart, baseEnd) + "\n" + ratingCss.slice(dashboardStart)).replaceAll("#summerRatingMonthSummaries", ".home-summer-dashboard");
fs.writeFileSync(path.join(root, "styles-home-summer-results.css"), "/* Generated by generate-home-summer-summary.js */\n" + sharedCss + "\n.home-summer-dashboard { padding: 12px 0; }\n.home-summer-dashboard > a { display: block; margin: 14px 0; color: #e8cd91; }\n");
fs.appendFileSync(path.join(root, "styles-home-summer-results.css"), `
/* Home summary uses the same unframed scene as the daily rating. */
.home-summer-dashboard .summer-results-hero {
  display: block; position: relative; aspect-ratio: 2; min-height: 0;
  border: 0; border-radius: 0; background: transparent; box-shadow: none; overflow: visible;
}
.home-summer-dashboard .summer-results-hero::before {
  content: ""; position: absolute; inset: 0;
  background: url('./assets/summer-results-hammocks-trio-v2.webp') center / cover no-repeat;
  mask-image: linear-gradient(to bottom, transparent, #000 9%, #000 78%, transparent), linear-gradient(to right, transparent, #000 5%, #000 95%, transparent);
  mask-composite: intersect; pointer-events: none;
}
.home-summer-dashboard .summer-results-hero__art { display: none; }
.home-summer-dashboard .summer-results-hero__copy { position: absolute; inset: 5% 0 auto; width: 100%; margin: 0; padding: 0; }
.home-summer-dashboard .summer-results-hero h2 { text-align: center; font-size: clamp(20px, 4.4vw, 42px); color: #ffe0a0; }
.home-summer-dashboard .summer-results-hero__total { width: 60%; margin: 4% 0 0 5%; border: 0; padding: 0; }
.home-summer-dashboard .summer-results-hero__total > span { font-size: clamp(8px, 1.4vw, 16px); }
.home-summer-dashboard .summer-results-hero__total strong { margin-top: 1%; font-size: clamp(25px, 5vw, 54px); color: #ffd477; text-shadow: 0 2px 8px #000; }
`);
const indexPath = path.join(root, "index.html");
const index = fs.readFileSync(indexPath, "utf8");
const marker = /<!-- home-summer-results:start -->[\s\S]*?<!-- home-summer-results:end -->/;
if (!marker.test(index)) throw new Error("Home summer results markers are missing");
fs.writeFileSync(indexPath, index.replace(marker, `<!-- home-summer-results:start -->\n${html}\n<!-- home-summer-results:end -->`));
console.log("Home summer results:", totals);
