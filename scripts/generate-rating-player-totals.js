const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const sources = [
  "winter-rating-data.js",
  "spring-rating-data-march.js",
  "spring-rating-data-april.js",
  "spring-rating-data-may.js",
  "summer-rating-data-june.js",
  "summer-rating-data-july.js",
  "summer-rating-data-august.js",
];
const context = vm.createContext({
  window: {},
  console,
  isFinite,
});

sources.forEach((file) => {
  vm.runInContext(fs.readFileSync(path.join(root, file), "utf8"), context, { filename: file });
});

function normalizeNick(value) {
  const original = value == null ? "" : String(value).trim();
  const lower = original.toLowerCase();
  if (lower === "pryanik2la") return "Пряник";
  if (lower === "фокс") return "Фокс";
  if (/^wa{3,5}r+$/.test(lower)) return "Waaar";
  if (lower === "andrushamorf" || lower === "4ezzi") return "FrankL";
  if (lower === "мужначас" || lower === "мужчина на час" || lower === "муж на час") return "Рыбнадзор";
  if (lower === "em13" || lower === "em13!!" || lower === "emil13" || lower === "еm13" || lower === "еm13!!") return "Em13!!";
  if (/^хер вам\)+$/.test(lower)) return "хер вам)))))";
  return original;
}

const totals = Object.create(null);
function addReward(nick, reward) {
  const normalized = normalizeNick(nick);
  if (!normalized) return;
  const key = normalized.toLocaleLowerCase("ru");
  totals[key] = (totals[key] || 0) + (Number(reward) || 0);
}
function addTournamentMap(map) {
  Object.keys(map || {}).forEach((date) => {
    (map[date] || []).forEach((tournament) => {
      (tournament && Array.isArray(tournament.players) ? tournament.players : []).forEach((player) => {
        addReward(player && player.nick, player && player.reward);
      });
    });
  });
}

const winterTournaments = context.WINTER_RATING_TOURNAMENTS_BY_DATE || {};
addTournamentMap(winterTournaments);
Object.keys(context.WINTER_RATING_BY_DATE || {}).forEach((date) => {
  if (Array.isArray(winterTournaments[date]) && winterTournaments[date].length) return;
  (context.WINTER_RATING_BY_DATE[date] || []).forEach((row) => addReward(row && row.nick, row && row.reward));
});
[
  context.SPRING_RATING_TOURNAMENTS_MARCH_BY_DATE,
  context.SPRING_RATING_TOURNAMENTS_APRIL_BY_DATE,
  context.SPRING_RATING_TOURNAMENTS_MAY_BY_DATE,
  context.SUMMER_RATING_TOURNAMENTS_JUNE_BY_DATE,
  context.SUMMER_RATING_TOURNAMENTS_JULY_BY_DATE,
  context.SUMMER_RATING_TOURNAMENTS_AUGUST_BY_DATE,
].forEach(addTournamentMap);

const sortedTotals = Object.keys(totals).sort((a, b) => a.localeCompare(b, "ru")).reduce((out, key) => {
  out[key] = Math.round(totals[key] * 100) / 100;
  return out;
}, {});
const output =
  "/* Generated by scripts/generate-rating-player-totals.js. */\n" +
  "(function () {\n" +
  "  var totals = " + JSON.stringify(sortedTotals) + ";\n" +
  "  window.pokerGetRatingPlayerTotalRewardFast = function (nick) {\n" +
  "    var key = String(nick || \"\").trim().toLocaleLowerCase(\"ru\");\n" +
  "    return Number(totals[key]) || 0;\n" +
  "  };\n" +
  "}());\n";

fs.writeFileSync(path.join(root, "rating-player-totals.js"), output);
console.log("Generated rating-player-totals.js for", Object.keys(sortedTotals).length, "players");
